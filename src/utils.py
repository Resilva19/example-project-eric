def winsorize_x(x, cuts=(0.01, 0.01)):
    """Winsorize a pandas Series at the given lower and upper quantile cuts.

    The default is 1%/99% winsorization, matching R's winsorize_x().

    Parameters
    ----------
    x    : array-like (pandas Series or numpy array)
    cuts : tuple of (lower_cut, upper_cut) as fractions, default (0.01, 0.01)

    Returns
    -------
    numpy array with extreme values clipped to the quantile bounds.

    EXAMPLE:
        data["roa"] = winsorize_x(data["roa"])
        # 2.5%/97.5% version:
        data["roa"] = winsorize_x(data["roa"], cuts=(0.025, 0.025))
    """
    arr = np.asarray(x, dtype=float)
    cut_bottom = np.nanquantile(arr, cuts[0])
    cut_top    = np.nanquantile(arr, 1 - cuts[1])
    return np.clip(arr, cut_bottom, cut_top)


def truncate_x(x, cuts=(0.01, 0.01)):
    """Truncate a pandas Series by setting extreme values to NaN.

    Unlike winsorize_x() which clips values to the quantile bounds,
    truncate_x() sets values outside the bounds to NaN, removing them
    from analysis. This is the Python equivalent of R's truncate_x().

    Parameters
    ----------
    x    : array-like (pandas Series or numpy array)
    cuts : tuple of (lower_cut, upper_cut) as fractions, default (0.01, 0.01)
    """
    arr = np.asarray(x, dtype=float).copy()
    cut_bottom = np.nanquantile(arr, cuts[0])
    cut_top    = np.nanquantile(arr, 1 - cuts[1])
    arr[arr >= cut_top]    = np.nan
    arr[arr <= cut_bottom] = np.nan
    return arr



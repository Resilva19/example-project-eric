# dplyr::case_when(). It evaluates conditions in order and returns the first
# matching value — identical semantics to case_when.
#
# USAGE:
#   data["FF12"]    = assign_FF12(data["sic4"])
#   data["ff12num"] = assign_FF12_num(data["sic4"])
#   data["FF49"]    = assign_FF49(data["sic4"])
#   data["ff49num"] = assign_FF49_num(data["sic4"])



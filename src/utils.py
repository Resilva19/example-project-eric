# Python Utilities for the example-project ------------------------------------
#
# This file is the Python equivalent of utils.R.
# It provides the same helper functions used across the analysis scripts:
#   - assign_FF12 / assign_FF12_num : Fama-French 12-industry classification
#   - assign_FF49 / assign_FF49_num : Fama-French 49-industry classification
#   - winsorize_x                   : winsorize a variable at given quantile cuts
#   - truncate_x                    : truncate (set to NaN) outside quantile cuts
#   - write_parquet                 : write DataFrame to Parquet with gzip compression
#
# USAGE (import into other scripts):
#   from utils import assign_FF12, assign_FF12_num, assign_FF49, assign_FF49_num
#   from utils import winsorize_x, truncate_x, write_parquet
#
# Unlike R's source("src/utils.R"), Python uses explicit imports.


import numpy as np

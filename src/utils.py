# Parquet functions ------------------------------------------------------------

# Provides a write_parquet() function that mirrors the custom write_parquet()
# defined in utils.R: writes with gzip compression at level 5.
# The standard pyarrow.parquet.read_parquet() is the read equivalent.

def write_parquet(df, path):
    """Write a DataFrame to Parquet with gzip compression (level 5).

    This matches the R utils.R write_parquet() function which defaults to
    arrow::write_parquet(x, p, compression = "gzip", compression_level = 5).
    """
    table = pa.Table.from_pandas(df)
    pq.write_table(table, path, compression="gzip")


